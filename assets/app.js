const catalogState = {
  selectedBrandId: null,
  selectedModel: null
};

const state = { mode: 'shop', lang: 'ru' };
const marketFeed = document.getElementById('marketFeed');
const toggleButton = document.getElementById('modeToggle');
const toggleText = document.getElementById('toggleText');
const authForm = document.getElementById('authForm');
const phoneInput = document.getElementById('phoneInput');
const formNote = document.getElementById('formNote');
const langButton = document.getElementById('langToggle');

function applyTranslations() {
  const lang = state.lang;
  document.documentElement.lang = lang === 'ru' ? 'ru' : 'tg';
  document.body.setAttribute('data-lang', lang);
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.getAttribute('data-i18n');
    const value = translations[lang][key];
    if (value) {
      element.textContent = value;
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.getAttribute('data-i18n-placeholder');
    const value = translations[lang][key];
    if (value) {
      element.placeholder = value;
    }
  });
  if (langButton) {
    langButton.textContent = lang === 'ru' ? 'Тоҷикӣ' : 'Русский';
  }
}

function listingCardHtml(item, lang) {
  const title = lang === 'ru' ? item.titleRu : item.titleTj;
  const location = lang === 'ru' ? item.locationRu : item.locationTj;
  const badge = lang === 'ru' ? item.badgeRu : item.badgeTj;
  const price = lang === 'ru' ? item.priceRu : item.priceTj;
  return `
    <article class="listing-card compact-card">
      <img src="${item.image}" alt="${title}" />
      <div class="compact-card-body">
        <div class="listing-top compact-top">
          <span class="${item.badgeClass}">${badge}</span>
          <span class="price">${price}</span>
        </div>
        <h3>${title}</h3>
        <p>${location}</p>
      </div>
    </article>
  `;
}

function renderListings() {
  if (!marketFeed) return;
  if (marketFeed.dataset.feedCategory && marketFeed.dataset.feedCategory !== 'home') return;
  const items = state.mode === 'shop' ? shopItems : privateItems;
  const lang = state.lang;
  marketFeed.innerHTML = items.map((item) => listingCardHtml(item, lang)).join('');
}

function shuffleItems(items, limit) {
  return [...items].sort(() => Math.random() - 0.5).slice(0, limit);
}

function renderFeedItems(items, feedElement) {
  if (!feedElement) return;
  const lang = state.lang;
  feedElement.classList.add('is-switching');
  window.setTimeout(() => {
    feedElement.innerHTML = items.map((item) => listingCardHtml(item, lang)).join('');
    feedElement.classList.remove('is-switching');
  }, 120);
}

function setMode(mode) {
  state.mode = mode;
  if (toggleButton) {
    toggleButton.classList.toggle('active', mode === 'private');
    toggleButton.setAttribute('aria-pressed', String(mode === 'private'));
  }
  if (toggleText) {
    toggleText.textContent = state.lang === 'ru'
      ? (mode === 'shop' ? translations.ru.toggleShop : translations.ru.togglePrivate)
      : (mode === 'shop' ? translations.tg.toggleShop : translations.tg.togglePrivate);
  }
  if (marketFeed) {
    marketFeed.classList.add('is-switching');
    window.setTimeout(() => {
      renderListings();
      marketFeed.classList.remove('is-switching');
    }, 160);
  }
}

function setLanguage(lang) {
  state.lang = lang;
  applyTranslations();
  setMode(state.mode);
  if (document.getElementById('brandGrid')) {
    renderAutoCatalogFeed();
  } else {
    renderRandomListings();
  }
}

langButton?.addEventListener('click', () => {
  setLanguage(state.lang === 'ru' ? 'tg' : 'ru');
});

toggleButton?.addEventListener('click', () => {
  setMode(state.mode === 'shop' ? 'private' : 'shop');
});

if (authForm) {
  authForm.addEventListener('submit', (event) => {
    event.preventDefault();
    const phone = phoneInput.value.trim();
    const valid = /^\+992\s?\d{9}$/.test(phone.replace(/\s+/g, ''));
    if (!valid) {
      formNote.textContent = translations[state.lang].authInvalid;
      return;
    }
    const method = document.getElementById('deliveryMethod').value.toUpperCase();
    formNote.textContent = `${translations[state.lang].authSent} ${method}.`;
  });
}

setLanguage('ru');
renderListings();
setMode('shop');

function renderRandomListings() {
  const feed = document.getElementById('marketFeed');
  if (!feed || feed.dataset.feedCategory === 'auto') return;

  const category = feed.dataset.feedCategory || 'mixed';
  let pool = [...shopItems, ...privateItems];
  if (category === 'auto') {
    pool = autoListings;
  }

  renderFeedItems(shuffleItems(pool, 4), feed);
}

function renderAutoCatalogFeed() {
  const feed = document.getElementById('marketFeed');
  const heading = document.getElementById('feedHeading');
  if (!feed || feed.dataset.feedCategory !== 'auto') return;

  let items = autoListings;
  if (catalogState.selectedBrandId && catalogState.selectedModel) {
    items = autoListings.filter(
      (item) =>
        item.brandId === catalogState.selectedBrandId &&
        item.model === catalogState.selectedModel
    );
    const brand = autoBrands.find((entry) => entry.id === catalogState.selectedBrandId);
    if (heading) {
      heading.textContent = `Объявления: ${brand?.name ?? ''} ${catalogState.selectedModel}`;
    }
  } else if (heading) {
    heading.textContent = 'Объявления — автомобили';
  }

  // Previously a placeholder card was added when no listings were found for a
  // selected brand/model. This caused “false card announcements” to appear in
  // the UI. The placeholder has been removed to keep the feed clean – if
  // there are no items, the feed simply shows nothing.
  if (catalogState.selectedBrandId && catalogState.selectedModel && items.length === 0) {
    items = [];
  }

  const displayItems = catalogState.selectedModel
    ? items
    : shuffleItems(autoListings, 4);

  renderFeedItems(displayItems, feed);
}

function initAutoBrandsPage() {
  const brandGrid = document.getElementById('brandGrid');
  const modelsShell = document.getElementById('modelsShell');
  const modelsGrid = document.getElementById('modelsGrid');
  const modelsHeading = document.getElementById('modelsHeading');
  if (!brandGrid || !modelsShell || !modelsGrid) return;

  brandGrid.innerHTML = autoBrands
    .map(
      (brand) => `
        <button type="button" class="brand-picker" data-brand-id="${brand.id}">
          <h3>${brand.name}</h3>
          <p>${brand.models.length} моделей</p>
        </button>
      `
    )
    .join('');

  function renderModels(brand) {
    modelsHeading.textContent = `Модели ${brand.name}`;
    modelsGrid.innerHTML = brand.models
      .map((modelName) => {
        const count = autoListings.filter(
          (item) => item.brandId === brand.id && item.model === modelName
        ).length;
        const countLabel = count > 0 ? `${count}+ объявлений` : 'Новые объявления';
        return `
          <button type="button" class="model-picker" data-model="${modelName}">
            <span class="category-icon">🚗</span>
            <div>
              <h3>${modelName}</h3>
              <p>${countLabel}</p>
            </div>
          </button>
        `;
      })
      .join('');

    modelsGrid.querySelectorAll('.model-picker').forEach((button) => {
      button.addEventListener('click', () => {
        catalogState.selectedModel = button.dataset.model;
        modelsGrid.querySelectorAll('.model-picker').forEach((el) => {
          el.classList.toggle('is-active', el === button);
        });
        renderAutoCatalogFeed();
      });
    });
  }

  brandGrid.querySelectorAll('.brand-picker').forEach((button) => {
    button.addEventListener('click', () => {
      const brandId = button.dataset.brandId;
      const brand = autoBrands.find((entry) => entry.id === brandId);
      if (!brand) return;

      const isSameBrand = catalogState.selectedBrandId === brandId;
      catalogState.selectedBrandId = isSameBrand ? null : brandId;
      catalogState.selectedModel = null;

      brandGrid.querySelectorAll('.brand-picker').forEach((el) => {
        el.classList.toggle('is-active', el.dataset.brandId === catalogState.selectedBrandId);
      });

      if (catalogState.selectedBrandId) {
        modelsShell.hidden = false;
        requestAnimationFrame(() => modelsShell.classList.add('is-open'));
        renderModels(brand);
      } else {
        modelsShell.classList.remove('is-open');
        modelsShell.addEventListener(
          'transitionend',
          function onClose(event) {
            if (event.propertyName !== 'max-height') return;
            modelsShell.removeEventListener('transitionend', onClose);
            if (!modelsShell.classList.contains('is-open')) {
              modelsShell.hidden = true;
            }
          },
          { once: false }
        );
      }

      renderAutoCatalogFeed();
    });
  });

  renderAutoCatalogFeed();
}

if (document.getElementById('brandGrid')) {
  initAutoBrandsPage();
} else {
  renderRandomListings();
}
